const SUPER_SELF_CONCEPT_QUESTION = 'سؤال مقترح من نظرية سوبر: بدل سؤاله مباشرة “أي تخصص تحب؟”، جرّب “كيف تحب الناس يشوفونك بعد ١٠ سنوات؟” — أحياناً يكشف صورة ذاتية أوضح من التخصص نفسه.';

function catByKey(def, key) {
  return def.categories.find(c => c.key === key);
}

function maxTotal(def) {
  return def.categories.reduce((n, c) => n + c.items.length, 0);
}

function computeScores(def, answers) {
  const scores = {};
  def.categories.forEach(cat => {
    scores[cat.key] = cat.items.reduce((n, _, i) => n + (answers[cat.key + '-' + i] ? 1 : 0), 0);
  });
  return scores;
}

function summarize(def, scores) {
  if (def.scoring === 'topN') {
    const code = def.categories
      .map(c => c.key)
      .sort((a, b) => scores[b] - scores[a])
      .slice(0, def.topN || 3)
      .join('');
    return { type: 'topN', code: code };
  }
  const total = Object.values(scores).reduce((a, b) => a + b, 0);
  const band = (def.bands || []).find(b => total >= b.min && total <= b.max) || null;
  return { type: 'sum', total: total, band: band };
}

// طبقة التفسير: نصوص جاهزة معرَّفة مسبقاً تُختار بقواعد ثابتة — بلا تحليل آلي
function interpret(def, scores, result) {
  if (result.type === 'topN') {
    const topCat = catByKey(def, result.code[0]);
    const out = [];
    if (topCat && topCat.tip) out.push({ kind: 'practical', text: topCat.tip, studentText: topCat.studentText || '', examples: topCat.examples || [] });
    out.push({ kind: 'question', text: SUPER_SELF_CONCEPT_QUESTION, examples: [] });
    return out;
  }
  const notes = [];
  if (result.band && result.band.guidance) notes.push({ kind: 'practical', text: result.band.guidance, studentText: result.band.studentText || '', examples: [] });
  if (result.band && result.band.theoryNote) notes.push({ kind: 'theory', text: result.band.theoryNote, examples: [] });
  let weakest = null, weakestRatio = 1;
  def.categories.forEach(c => {
    const ratio = (scores[c.key] || 0) / c.items.length;
    if (ratio < weakestRatio) { weakestRatio = ratio; weakest = c; }
  });
  if (weakest && weakestRatio < 0.5) {
    if (weakest.tip) notes.push({ kind: 'practical', text: weakest.tip, studentText: weakest.studentText || '', examples: weakest.examples || [] });
    if (weakest.theoryNote) notes.push({ kind: 'theory', text: weakest.theoryNote, examples: [] });
  }
  return notes;
}

function newId() {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) return crypto.randomUUID();
  return Date.now() + '-' + Math.random().toString(36).slice(2, 10);
}

